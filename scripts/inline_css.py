#!/usr/bin/env python3
"""Inline the site's CSS into each page and emit the font preloads.

Why: the stylesheet set is small and it is the only render-blocking resource left.
Serving it as five linked files costs five round trips before the first paint and
Lighthouse scores it as ~1.2s of render-blocking time on a throttled phone. Inlined,
the first paint needs zero CSS requests, and the only bytes before text are the two
font files — which are preloaded so the swap lands in the same frame rather than
after it.

The sources stay in assets/ (fonts.css, base.css, dir06.css, site.css, ratio.css);
this script is the only thing that knows how to put them in a page. Run it after any
CSS or page edit. `--check` fails if a page's inline block is stale, which is what
the deploy workflow runs — so a forgotten rebuild cannot ship.

usage:
  python3 scripts/inline_css.py            # write the pages
  python3 scripts/inline_css.py --check    # verify, exit 1 if stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["assets/fonts/fonts.css", "assets/base.css", "assets/dir06.css",
           "assets/site.css", "assets/ratio.css"]
PAGES = ["index.html", "pages/services.html", "pages/work.html", "pages/learn.html",
         "pages/merch.html", "pages/giveaways.html", "pages/affiliates.html"]
BEGIN = "<!-- inline-css:begin (generated by scripts/inline_css.py) -->"
END = "<!-- inline-css:end -->"
FONTS = ["inter-latin-subset.woff2", "jetbrains-mono-latin-subset.woff2"]


def minify(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{};:,>])\s*", r"\1", css)
    css = re.sub(r";}", "}", css)
    return css.strip()


def block(prefix):
    parts = []
    for rel in SOURCES:
        css = open(os.path.join(ROOT, rel)).read()
        # fonts.css refers to its files by bare name; from the page root they are
        # two directories away, so rebase every url() before inlining
        css = re.sub(r"url\(([^)]+)\)", lambda m: "url(%sassets/fonts/%s)" % (prefix, m.group(1).strip()),
                     css)
        parts.append(f"/* {rel} */\n" + css)
    preloads = "\n".join(
        f'<link rel="preload" href="{prefix}assets/fonts/{f}" as="font" type="font/woff2" crossorigin>'
        for f in FONTS)
    return f"{BEGIN}\n{preloads}\n<style>{minify(chr(10).join(parts))}</style>\n{END}"


def apply(path, prefix, check):
    src = open(path).read()
    new = block(prefix)
    if BEGIN in src:
        out = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: new, src, flags=re.S)
    else:
        # drop the five link tags this block replaces
        out = re.sub(r'\n<link rel="stylesheet" href="[^"]*(?:fonts/fonts|base|dir06|site|ratio)\.css">', "", src)
        out = out.replace("<link rel=\"icon\"", new + "\n<link rel=\"icon\"", 1)
    if check:
        return out == src
    if out != src:
        open(path, "w").write(out)
    return True


def main():
    check = "--check" in sys.argv
    stale = []
    for page in PAGES:
        prefix = "" if "/" not in page else "../"
        ok = apply(os.path.join(ROOT, page), prefix, check)
        if check and not ok:
            stale.append(page)
    if check:
        if stale:
            print("STALE inline CSS:", ", ".join(stale))
            print("run: python3 scripts/inline_css.py")
            return 1
        print("inline CSS: all pages current")
        return 0
    print("inline CSS: pages written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
